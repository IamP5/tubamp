#!/usr/bin/env python3
"""tubamp phaser voicings: offline reference (numpy only).

Two voicings, both four first-order allpass stages built as TPT (trapezoidal) one-poles whose
coefficients are solved per sweep position so that the rendered notches land on the analog
prototype's at any sample rate (voicings.md, "Shared building block"; stage_g, coeff_table);
the feedback loops are solved without a unit delay:

  phase90     JFET-leg sweep law (exponential channel resistance, soft-limited by a series
              resistance, 22k in parallel), 50/50 mix. --block adds the block-logo feedback
              resistor (R15 in Eichas' schematic): wet = A . S2 . A^2 / (1 + beta L A^2), beta
              fitted, L a one-pole lag in that feedback path (fitted to the notch depth).
  smallstone  exponential sweep (Color off: with a small curvature term), the wet input through a
              first-order highpass, wet dominant. --color instead adds feedback around all four
              stages through a second-order highpass branch, a second-order shaping branch on the
              wet input (both from one two-pole network), a lower sweep range and a wet-heavy mix.

    phaser_ref.py in.wav out.wav --voicing phase90 [--block] [--rate 1.0] [--depth 0.5] [--mix 0.5]
    phaser_ref.py in.wav out.wav --voicing smallstone [--color] [--rate 0.32] [--depth 0.5] [--mix 0.5]

depth 0.5 and mix 0.5 are the stock pedal; the output includes the voicing's make-up gain
(render(makeup=False) leaves it out). Every constant is tagged in ../voicings.md.
[fit] constants are regenerated by ../evidence/fit/fit.py from ../evidence/fit/targets.tsv,
../evidence/fit/trajectories.tsv (the Phase 90 sweep law, LFO and gate smoothing) and
../evidence/fit/snapshots.tsv (complex responses: Small Stone Color off, both sweep ranges).
render() also accepts x of shape (frames, channels); channels are processed in parallel.
This file is the specification of the algorithm, not shipping code: it runs per sample
in Python and takes a few seconds per ten seconds of audio.
"""
import argparse
import math
import struct
import sys

import numpy as np

# ---------------------------------------------------------------- Phase 90 constants
P90_C = 47e-9            # allpass capacitor, F                                   [circuit]
P90_RFIX = 22e3          # resistor in parallel with each JFET, ohm               [circuit]
P90_RS = 916.8           # JFET leg: series resistance that limits the channel at the sweep top, ohm [fit]
P90_R1 = 1777.7          # JFET leg: channel resistance at mid-sweep (u = 0), ohm                [fit]
P90_GAMMA = 0.8952       # JFET leg: R_ch = R1 exp(-gamma u), u the smoothed LFO in [-1, 1]      [fit]
P90_KNEE = 3.876         # JFET leg: R = (RS^m + R_ch^m)^(1/m), sharpness m of the series limit  [fit]
P90_BETA = 0.3957        # block logo: op-amp feedback resistor / feedback resistor (R15 in Eichas) [fit]
P90_KAPPA = -0.007      # LFO curvature: RC charge halves, 0 = straight triangle                [fit]
P90_GATE_HZ = 3.542      # one-pole smoothing between LFO and JFET gates                          [fit]
P90_FB_LAG_HZ = 14746.0  # block logo: one-pole lag in the feedback-resistor path (sets notch depth) [fit]

# ------------------------------------------------------------- Small Stone constants
# Color off: the wet input through a first-order highpass at f_hp, wet dominant; ln fc carries a curvature
# term curve * (v^2 - 1). All values: fit.py from the complex snapshots (snapshots.tsv), kappa fixed.  [fit]
SS_OFF = dict(f_lo=326.4, f_hi=9086.3, curve=0.0128, c=0.0, dry=0.5003, wet=0.7500, f_hp=44.2)
# Color on: feedback c around all four stages through the Color network's highpass branch, the
# wet input through its shaping branch. The network has two real poles f_p1 < f_p2 shared by
# both branches (one RC network, two taps). Structure: fit.py from targets.tsv; f_lo, f_hi from snapshots.tsv. [fit]
SS_ON = dict(f_lo=98.5, f_hi=3105.4, c=0.7548, dry=0.1318, wet=0.4395,
             f_p1=49.8, f_p2=267.9,      # network poles, Hz
             f_zf=12.0,                  # feedback branch zero (second zero is at DC), Hz
             f_za=12.7, f_zb=862.1)      # input branch zeros, Hz
SS_KAPPA = 0.702          # LFO curvature (trajectories.tsv, Color off)

# ------------------------------------------------------------------- make-up gains
# Output gain per voicing, linear: unity K-weighted loudness against bypass, averaged over three
# guitar-like takes in three registers (voicings.md, "Level"; check_phaser.py P18).
P90_SCRIPT_MAKEUP = 1.3152   # +2.38 dB                                               [choice]
P90_BLOCK_MAKEUP = 1.3137    # +2.37 dB                                               [choice]
SS_OFF_MAKEUP = 1.0186       # +0.16 dB                                               [choice]
SS_ON_MAKEUP = 0.9237        # -0.69 dB                                               [choice]

# ------------------------------------------------------------ discretisation (voicings.md)
TABLE_N = 256            # coefficient table: intervals over the sweep position [-1, 1]  [choice]
MATCH_CAP = 0.25         # highest matching frequency of pair_g, as a fraction of fs     [choice]
NOTCH_EPS = 1e-4         # half step in ln f of the notch condition                       [choice]
T8 = math.tan(math.pi / 8)


def read_wav(path):
    raw = open(path, "rb").read()
    pos, fmt, data = 12, None, None
    while pos + 8 <= len(raw):
        tag, size = raw[pos:pos + 4], struct.unpack("<I", raw[pos + 4:pos + 8])[0]
        chunk = raw[pos + 8:pos + 8 + size]
        if tag == b"fmt ":
            fmt = struct.unpack("<HHIIHH", chunk[:16])
        elif tag == b"data":
            data = chunk
        pos += 8 + size + (size & 1)
    code, channels, sr, _, _, bits = fmt
    if code == 0xFFFE:
        code = 3 if bits == 32 else 1
    if code == 3:
        samples = np.frombuffer(data, "<f4" if bits == 32 else "<f8").astype(np.float64)
    elif bits == 16:
        samples = np.frombuffer(data, "<i2") / 32768.0
    elif bits == 24:
        b = np.frombuffer(data, np.uint8).reshape(-1, 3).astype(np.int32)
        samples = ((b[:, 0] | (b[:, 1] << 8) | (b[:, 2] << 16)) << 8 >> 8) / 8388608.0
    else:
        samples = np.frombuffer(data, "<i4") / 2147483648.0
    return samples.reshape(-1, channels).T, sr


def write_wav(path, data, sr):
    data = np.atleast_2d(np.asarray(data, dtype=np.float32))
    channels, frames = data.shape
    body = data.T.astype("<f4").tobytes()
    header = b"RIFF" + struct.pack("<I", 36 + len(body)) + b"WAVEfmt " + struct.pack(
        "<IHHIIHH", 16, 3, channels, int(sr), int(sr) * channels * 4, channels * 4, 32)
    open(path, "wb").write(header + b"data" + struct.pack("<I", len(body)) + body)


def rc_triangle(phase, kappa):
    """Relaxation-oscillator triangle in [-1, 1]: each half is an RC charge curve.
    kappa -> 0 is a straight triangle. phase in [0, 1)."""
    up = phase < 0.5
    u = np.where(up, 2.0 * phase, 2.0 * phase - 1.0)
    s = u if abs(kappa) < 1e-9 else (1.0 - np.exp(-kappa * u)) / (1.0 - math.exp(-kappa))
    return np.where(up, 2.0 * s - 1.0, 1.0 - 2.0 * s)


def lfo(n, fs, rate_hz, kappa, phase0=0.0):
    return rc_triangle((phase0 + rate_hz * np.arange(n) / fs) % 1.0, kappa)


# ------------------------------------------------------------------- sweep laws
def phase90_leg_ohm(u):
    """Resistance of one stage's JFET leg against the smoothed LFO u (+1 = top of the sweep):
    an exponential channel resistance soft-limited from below by a series resistance."""
    r_ch = P90_R1 * np.exp(-P90_GAMMA * u)
    return (P90_RS ** P90_KNEE + r_ch ** P90_KNEE) ** (1.0 / P90_KNEE)


def phase90_fc(u):
    """Analog break frequency of the four Phase 90 stages at sweep position u."""
    return (1.0 / P90_RFIX + 1.0 / phase90_leg_ohm(u)) / (2.0 * math.pi * P90_C)


def smallstone_fc(w, color):
    """Analog break frequency of the four Small Stone stages at sweep position w: exponential in w, plus
    (Color off) a curvature term that leaves the ends at f_lo and f_hi."""
    p = SS_ON if color else SS_OFF
    w = np.asarray(w, float)
    return math.sqrt(p["f_lo"] * p["f_hi"]) * np.exp(0.5 * math.log(p["f_hi"] / p["f_lo"]) * w + p.get("curve", 0.0) * (w * w - 1.0))


def phase90_sweep(n, fs, rate_hz, depth, phase0=0.0):
    """Per-sample sweep position u of the Phase 90: LFO -> gate smoothing, scaled by depth/0.5."""
    v = lfo(n, fs, rate_hz, P90_KAPPA, phase0)
    k = 1.0 - math.exp(-2.0 * math.pi * P90_GATE_HZ / fs)       # gate RC
    s = v[0]
    for i in range(n):
        s += k * (v[i] - s)
        v[i] = s
    return v * (depth / 0.5)


def smallstone_sweep(n, fs, rate_hz, depth, phase0=0.0):
    """Per-sample sweep position of the Small Stone: the LFO, its log range scaled by depth/0.5
    (capped at 1.2)."""
    return lfo(n, fs, rate_hz, SS_KAPPA, phase0) * min(depth / 0.5, 1.2)


def phase90_break_hz(n, fs, rate_hz, depth, phase0=0.0):
    """Per-sample analog break frequency of the Phase 90 voicing."""
    return phase90_fc(phase90_sweep(n, fs, rate_hz, depth, phase0))


def smallstone_break_hz(n, fs, rate_hz, depth, color, phase0=0.0):
    return smallstone_fc(smallstone_sweep(n, fs, rate_hz, depth, phase0), color)


# ------------------------------------------------- analog prototypes and the notch condition
# The voicings are the analog transfer functions below. In them `sv` is the Laplace variable
# and g a one-pole's break: sv = j*f with g in Hz (analog), or, for the discretised filter,
# sv = j*tan(pi*f/fs) with g the TPT coefficient (the trapezoidal map on the unit circle).
def ap(sv, g):
    """(s - w)/(s + w): -1 at DC, +1 at HF (the Phase 90's op-amp stage; P = -A)."""
    return (sv - g) / (sv + g)


def lowpass(sv, g):
    return g / (g + sv)


def h_block(sv, g, gl):
    """Phase 90 block, wet and dry, no make-up: g = (stage 1, stage 2, stage 3, stage 4), gl the lag."""
    a34 = ap(sv, g[2]) * ap(sv, g[3])
    s2 = ((1.0 + P90_BETA) * sv - g[1]) / (sv + g[1])
    return 0.5 + 0.5 * ap(sv, g[0]) * s2 * a34 / (1.0 + P90_BETA * lowpass(sv, gl) * a34)


def h_stone_on(sv, g, gn1, gn2):
    """Small Stone Color on, no make-up: g the four stages, gn1/gn2 the Color network's poles."""
    p = SS_ON
    ka, kb, kf = 1.0 - p["f_za"] / p["f_p1"], 1.0 - p["f_zb"] / p["f_p2"], 1.0 - p["f_zf"] / p["f_p2"]
    p4 = ap(sv, g[0]) * ap(sv, g[1]) * ap(sv, g[2]) * ap(sv, g[3])
    ha = (1.0 - ka * lowpass(sv, gn1)) * (1.0 - kb * lowpass(sv, gn2))
    fb = (1.0 - lowpass(sv, gn1)) * (1.0 - kf * lowpass(sv, gn2))
    return p["dry"] + p["wet"] * ha * p4 / (1.0 - p["c"] * fb * p4)


def analog_sv(f):
    return 1j * f


def digital_sv(fs):
    return lambda f: 1j * math.tan(math.pi * f / fs)


def notch_condition(h, f):
    """Zero where |h| has a minimum or maximum at f: ln|h|^2 a step above f minus a step below."""
    up, dn = abs(h(f * math.exp(NOTCH_EPS))), abs(h(f * math.exp(-NOTCH_EPS)))
    return 2.0 * (math.log(up) - math.log(dn))


def newton(res, x0, iters=40, tol=1e-12, step=1e-7, clip=0.2):
    """Newton's method with a forward-difference Jacobian and a backtracking line search (the step,
    scaled down as a whole until no unknown moves by more than clip, is halved until the residual's
    sum of squares falls, at most 30 times); -> (x, converged)."""
    x = np.array(x0, float)
    r = np.asarray(res(x), float)
    for _ in range(iters):
        if not np.all(np.isfinite(r)):
            return x, False
        if np.max(np.abs(r)) < tol:
            return x, True
        jac = np.empty((len(r), len(x)))
        for j in range(len(x)):
            d = np.zeros(len(x)); d[j] = step
            jac[:, j] = (np.asarray(res(x + d), float) - r) / step
        try:
            dx = np.linalg.solve(jac, r)
        except np.linalg.LinAlgError:
            return x, False
        big = float(np.max(np.abs(dx)))
        if not math.isfinite(big):
            return x, False
        if big > clip:
            dx = dx * (clip / big)
        norm = float(np.sum(r * r))
        for _ in range(30):
            xn = x - dx
            rn = np.asarray(res(xn), float)
            if np.all(np.isfinite(rn)) and float(np.sum(rn * rn)) < norm:
                break
            dx = 0.5 * dx
        else:
            return x, False
        x, r = xn, rn
    return x, bool(np.all(np.isfinite(r)) and np.max(np.abs(r)) < 1e3 * tol)


def analog_notch(h, f0, lo, hi):
    """Frequency of the minimum of |h| reached by Newton from f0, or None if there is none in [lo, hi]."""
    x, ok = newton(lambda x: [notch_condition(h, math.exp(x[0]))], [math.log(f0)], step=1e-5)
    f = math.exp(x[0])
    if not ok or not lo <= f <= hi:
        return None
    if notch_condition(h, f * 1.001) <= 0.0:       # a maximum, not a notch
        return None
    return f


# ------------------------------------------------------------- discretisation (both voicings)
def warped_g(f_break, fs, f_match):
    """TPT coefficient of a one-pole with analog break f_break whose response is exact at f_match
    (f_match clamped to 0.49 fs before the tan)."""
    f_match = min(f_match, 0.49 * fs)
    return math.tan(math.pi * f_match / fs) * f_break / f_match


def pair_g(fc, fs, fa, fb):
    """Coefficients ga < gb of two one-pole allpasses, each used twice, whose four-stage chain has
    the phase of four analog stages at fc, -8 atan(f/fc), exactly at fa and at fb (fb capped at
    MATCH_CAP fs). With c = 1/g the condition at one frequency is linear in c_a + c_b and c_a c_b."""
    fb = min(fb, MATCH_CAP * fs)
    if fb > 1.0001 * fa:
        rows = []
        for f in (fa, fb):
            q, t = f / fc, math.tan(math.pi * f / fs)
            rows.append((t * (1.0 - q * q), 2.0 * q * t * t, 2.0 * q))
        (a1, b1, c1), (a2, b2, c2) = rows
        det = a1 * b2 - a2 * b1
        if det != 0.0:
            s, p = (c1 * b2 - c2 * b1) / det, (a1 * c2 - a2 * c1) / det
            r = math.sqrt(max(s * s - 4.0 * p, 0.0))
            if p > 0.0 and s > r and math.isfinite(s):
                return 2.0 / (s + r), 2.0 / (s - r)
    g = warped_g(fc, fs, fa)
    return g, g


def stage_g(voicing, fc, fs, start=None):
    """TPT coefficients (stage 1, 2, 3, 4, lag; lag 0 where unused) at analog break frequency fc,
    and the solved unknowns. `start` is the neighbouring table entry's solution: the solve starts
    there and, where it does not converge, keeps it (continuation along the sweep).

    script, off  pair_g at the frequencies where four analog stages give -180 and -540 degrees
                 (tan(pi/8) fc, tan(3pi/8) fc): both notches land on the analog ones.
    on           the same pair, both scaled by one factor so that notch 1 of the whole Color loop
                 lands on the analog loop's notch 1 (factor 1 where the analog response has none).
    block        stage 2 and the lag exact at the analog notch 1 (n1); stages 3 and 4 a pair_g
                 matched at n1 and n2; then stage 1, the scale and the spread of the 3/4 pair are
                 solved so that both notches land on n1, n2 and the notch-1 depth equals the analog."""
    fc = float(fc)
    if voicing in ("script", "off"):
        ga, gb = pair_g(fc, fs, T8 * fc, fc / T8)
        return (ga, gb, ga, gb, 0.0), []
    dsv = digital_sv(fs)
    if voicing == "on":
        ga, gb = pair_g(fc, fs, T8 * fc, fc / T8)
        gn1, gn2 = math.tan(math.pi * SS_ON["f_p1"] / fs), math.tan(math.pi * SS_ON["f_p2"] / fs)
        ha = lambda f: h_stone_on(analog_sv(f), (fc,) * 4, SS_ON["f_p1"], SS_ON["f_p2"])  # noqa: E731
        n1 = analog_notch(ha, 0.42 * fc, 0.3 * fc, 0.8 * fc)
        x = [0.0]
        if n1 is not None and n1 * math.exp(NOTCH_EPS) < 0.45 * fs:
            x0 = list(start) if start else [0.0]
            hd = lambda k, f: h_stone_on(dsv(f), (ga * k, gb * k) * 2, gn1, gn2)  # noqa: E731
            xs, ok = newton(lambda v: [notch_condition(lambda f: hd(math.exp(v[0]), f), n1)], x0)
            x = list(xs) if ok else x0
        k = math.exp(x[0])
        return (ga * k, gb * k, ga * k, gb * k, 0.0), x
    ha = lambda f: h_block(analog_sv(f), (fc,) * 4, P90_FB_LAG_HZ)  # noqa: E731
    n1 = analog_notch(ha, 0.45 * fc, 0.3 * fc, 0.65 * fc)
    n2 = analog_notch(ha, 2.07 * fc, 1.4 * fc, 3.0 * fc)
    if n1 is None:
        g = warped_g(fc, fs, T8 * fc)
        return (g, g, g, g, warped_g(P90_FB_LAG_HZ, fs, T8 * fc)), []
    gs, gl = warped_g(fc, fs, n1), warped_g(P90_FB_LAG_HZ, fs, n1)
    g3, g4 = pair_g(fc, fs, n1, n2 if n2 is not None else fc / T8)
    if n2 is None or n2 * math.exp(NOTCH_EPS) >= 0.45 * fs:
        return (gs, gs, g3, g4, gl), []
    depth = math.log(abs(ha(n1)))

    def gains(x):
        return (gs * math.exp(x[0]), gs, g3 * math.exp(x[1] + x[2]), g4 * math.exp(x[1] - x[2]))

    def res(x):
        h = lambda f: h_block(dsv(f), gains(x), gl)  # noqa: E731
        return [notch_condition(h, n1), notch_condition(h, n2), math.log(abs(h(n1))) - depth]
    x0 = list(start) if start and len(start) == 3 else [0.0, 0.0, 0.0]
    xs, ok = newton(res, x0)
    x = list(xs) if ok else x0
    return (*gains(x), gl), x


_TABLES = {}


def coeff_table(voicing, fs, wmax=1.0):
    """(TABLE_N + 1) x 5 table of TPT G = g/(1+g) (stages 1-4, lag) at sweep positions
    linspace(-wmax, wmax, TABLE_N + 1); voicing script, block, off or on."""
    key = (voicing, float(fs), float(wmax), P90_RS, P90_R1, P90_GAMMA, P90_KNEE, P90_FB_LAG_HZ, P90_BETA,
           tuple(SS_OFF.values()), tuple(SS_ON.values()))
    if key not in _TABLES:
        w = np.linspace(-wmax, wmax, TABLE_N + 1)
        fcs = phase90_fc(w) if voicing in ("script", "block") else smallstone_fc(w, voicing == "on")
        rows, sol = [], None
        for fc in fcs:                      # from the sweep bottom up, each solve starting at the last
            g, sol = stage_g(voicing, fc, fs, sol)
            rows.append(g)
        g = np.array(rows)
        _TABLES[key] = g / (1.0 + g)
    return _TABLES[key]


def lookup(table, w, wmax=1.0):
    """Per-sample coefficients: linear interpolation of the table at sweep positions w."""
    t = np.clip((np.asarray(w, float) + wmax) * (0.5 * TABLE_N / wmax), 0.0, float(TABLE_N))
    i = np.minimum(np.floor(t).astype(int), TABLE_N - 1)
    fr = (t - i)[:, None]
    return table[i] + fr * (table[i + 1] - table[i])


# ------------------------------------------------------------------- the per-sample loops
def run_phase90(x, fs, G, block, mix, makeup=1.0):
    """G: per-sample (n, 5) TPT coefficients (stages 1-4, lag). A(v) = v - 2 lp per stage."""
    beta = P90_BETA if block else 0.0
    s1 = s2 = s3 = s4 = sl = 0.0
    y = np.empty(np.shape(x))      # x: (frames,) or (frames, channels)
    for n in range(len(x)):
        G1, G2, G3, G4, GL = G[n]
        xin = x[n]
        v = (xin - s1) * G1; lp = v + s1; s1 = lp + v
        v1 = xin - 2.0 * lp
        v = (v1 - s2) * G2; lp = v + s2; s2 = lp + v
        if block:
            # stage 2 gains 2+beta (the feedback resistor loads its inverting input); stages 3 and 4
            # sit in the loop u = s2out - beta*L(y4), solved without a delay:
            #   L(y4) = GL*y4 + (1-GL)*sl,  y4 = a4*(a3*u + k3) + k4
            s2out = (1.0 + beta) * v1 - (2.0 + beta) * lp
            a3, a4 = 1.0 - 2.0 * G3, 1.0 - 2.0 * G4
            k3, k4 = -2.0 * (1.0 - G3) * s3, -2.0 * (1.0 - G4) * s4
            y4 = (a4 * (a3 * (s2out - beta * (1.0 - GL) * sl) + k3) + k4) / (1.0 + beta * GL * a3 * a4)
            v = (y4 - sl) * GL; lp = v + sl; sl = lp + v
            u = s2out - beta * lp
        else:
            u = v1 - 2.0 * lp
        v = (u - s3) * G3; lp = v + s3; s3 = lp + v
        y3 = u - 2.0 * lp
        v = (y3 - s4) * G4; lp = v + s4; s4 = lp + v
        y[n] = makeup * ((1.0 - mix) * xin + mix * (y3 - 2.0 * lp))
    return y


def run_smallstone(x, fs, G, color, mix, makeup=1.0):
    """G: per-sample (n, 4+) TPT coefficients of the four stages. P = (1-w)/(1+w) per stage.
    mix 0.5 is the stock dry/wet pair, 0 dry, 1 wet only.

    Color off: the stages' input is the input highpassed at f_hp, u = x - lp_hp(x).
    Color on (all one-poles are TPT lowpasses lp = G*(in - s) + s, s <- 2*lp - s):
      input branch    xs = Sb(Sa(x)),  Sa(v) = v - (1 - f_za/f_p1) * lp1a(v),  Sb(v) = v - (1 - f_zb/f_p2) * lp2a(v)
                      = (s + w_za)(s + w_zb) / ((s + w_p1)(s + w_p2))
      feedback branch F(y) = Sf(y - lp1f(y)),  Sf(v) = v - (1 - f_zf/f_p2) * lp2f(v)
                      = s (s + w_zf) / ((s + w_p1)(s + w_p2))
      loop            u = xs + c * F(y4),  y4 = P4(P3(P2(P1(u)))), solved per sample without a delay
      out             dry * x + wet * y4
    """
    p = SS_ON if color else SS_OFF
    c = p["c"]
    dry = p["dry"] * min(1.0, 2.0 * (1.0 - mix))
    wet = p["wet"] * min(1.0, 2.0 * mix)
    if color:
        G1, G2 = tpt_g(p["f_p1"], fs), tpt_g(p["f_p2"], fs)
        ka, kb, kf = 1.0 - p["f_za"] / p["f_p1"], 1.0 - p["f_zb"] / p["f_p2"], 1.0 - p["f_zf"] / p["f_p2"]
        aF = (1.0 - G1) * (1.0 - kf * G2)     # instantaneous gain of F
    else:
        Gh = tpt_g(p["f_hp"], fs)
    st = [0.0, 0.0, 0.0, 0.0]
    s1a = s2a = 0.0  # input branch states
    s1f = s2f = 0.0  # feedback branch states
    sh = 0.0         # Color off highpass state
    y = np.empty(np.shape(x))      # x: (frames,) or (frames, channels)
    for n in range(len(x)):
        Gs = G[n]
        xin = x[n]
        if color:
            K, p4 = 0.0, 1.0      # y4 = p4 * u + K
            for k in range(4):
                pk = 2.0 * Gs[k] - 1.0
                K = pk * K + 2.0 * (1.0 - Gs[k]) * st[k]
                p4 *= pk
            v = (xin - s1a) * G1; lp = v + s1a; s1a = lp + v
            xa = xin - ka * lp
            v = (xa - s2a) * G2; lp = v + s2a; s2a = lp + v
            xs = xa - kb * lp
            # F(y4) = aF * y4 + bF  (affine in y4 for this sample)
            bF = -(1.0 - kf * G2) * (1.0 - G1) * s1f - kf * (1.0 - G2) * s2f
            y4 = (p4 * (xs + c * bF) + K) / (1.0 - c * aF * p4)
            v = (y4 - s1f) * G1; lp = v + s1f; s1f = lp + v
            h = y4 - lp
            v = (h - s2f) * G2; lp = v + s2f; s2f = lp + v
            u = xs + c * (h - kf * lp)
        else:
            v = (xin - sh) * Gh; lp = v + sh; sh = lp + v
            u = xin - lp
        for k in range(4):
            v = (u - st[k]) * Gs[k]; lp = v + st[k]; st[k] = lp + v
            u = 2.0 * lp - u
        y[n] = makeup * (dry * xin + wet * u)
    return y


def tpt_g(f_hz, fs):
    g = math.tan(math.pi * f_hz / fs)
    return g / (1.0 + g)


def render(x, fs, voicing, rate=1.0, depth=0.5, mix=0.5, block=False, color=False, makeup=True, phase0=0.0):
    """makeup=False leaves out the voicing's make-up gain (fits and comparisons against Guitar Rig
    6, whose own make-up is removed from targets.tsv)."""
    n = len(x)
    if voicing == "phase90":
        name, wmax = ("block" if block else "script"), max(1.0, depth / 0.5)
        G = lookup(coeff_table(name, fs, wmax), phase90_sweep(n, fs, rate, depth, phase0), wmax)
        gain = (P90_BLOCK_MAKEUP if block else P90_SCRIPT_MAKEUP) if makeup else 1.0
        return run_phase90(x, fs, G, block, mix, gain)
    name, wmax = ("on" if color else "off"), max(1.0, min(depth / 0.5, 1.2))
    G = lookup(coeff_table(name, fs, wmax), smallstone_sweep(n, fs, rate, depth, phase0), wmax)
    gain = (SS_ON_MAKEUP if color else SS_OFF_MAKEUP) if makeup else 1.0
    return run_smallstone(x, fs, G, color, mix, gain)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("inp"); ap.add_argument("out")
    ap.add_argument("--voicing", choices=("phase90", "smallstone"), required=True)
    ap.add_argument("--block", action="store_true"); ap.add_argument("--color", action="store_true")
    ap.add_argument("--rate", type=float, default=None)
    ap.add_argument("--depth", type=float, default=0.5); ap.add_argument("--mix", type=float, default=0.5)
    a = ap.parse_args()
    x, fs = read_wav(a.inp)
    rate = a.rate if a.rate is not None else (1.0 if a.voicing == "phase90" else 0.32)
    out = [render(ch, fs, a.voicing, rate, a.depth, a.mix, a.block, a.color) for ch in x]
    write_wav(a.out, np.array(out), fs)
    print(f"{a.out}\t{len(x[0])} frames\t{fs} Hz\tpeak {20*np.log10(np.max(np.abs(out))+1e-12):.2f} dBFS", file=sys.stderr)


if __name__ == "__main__":
    main()
