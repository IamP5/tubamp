#!/usr/bin/env python3
"""tubamp phaser voicings: offline reference (numpy only).

Two voicings, both four first-order allpass stages built as TPT (trapezoidal) one-poles,
so the break frequency is exact at any sample rate and the feedback loops are solved
without a unit delay:

  phase90     JFET-leg sweep law (exponential channel resistance, soft-limited by a series
              resistance, 22k in parallel), 50/50 mix. --block adds the block-logo feedback
              resistor (R15 in Eichas' schematic): wet = A . S2 . A^2 / (1 + beta L A^2), beta
              fitted, L a one-pole lag in that feedback path (fitted to the notch depth).
  smallstone  exponential sweep. --color adds feedback around all four stages through a
              second-order highpass branch, a second-order shaping branch on the wet input
              (both from one two-pole network), a lower sweep range and a wet-heavy mix.

    phaser_ref.py in.wav out.wav --voicing phase90 [--block] [--rate 1.0] [--depth 0.5] [--mix 0.5]
    phaser_ref.py in.wav out.wav --voicing smallstone [--color] [--rate 0.32] [--depth 0.5] [--mix 0.5]

depth 0.5 and mix 0.5 are the stock pedal. Every constant is tagged in ../voicings.md.
[fit] constants are regenerated by ../evidence/fit/fit.py from ../evidence/fit/targets.tsv and
../evidence/fit/trajectories.tsv (the Phase 90 sweep law, LFO and gate smoothing: trajectories).
render() also accepts x of shape (frames, channels); channels are processed in parallel.
This file is the specification of the algorithm, not shipping code: it runs per sample
in Python and takes a few seconds per ten seconds of audio.
"""
import argparse
import math
import struct
import sys

import numpy as np

# ---------------------------------------------------------------- Phase 90 constants
P90_C = 47e-9            # allpass capacitor, F                                   [circuit]
P90_RFIX = 22e3          # resistor in parallel with each JFET, ohm               [circuit]
P90_RS = 933.7           # JFET leg: series resistance that limits the channel at the sweep top, ohm [fit]
P90_R1 = 1786.1          # JFET leg: channel resistance at mid-sweep (u = 0), ohm                [fit]
P90_GAMMA = 0.8915       # JFET leg: R_ch = R1 exp(-gamma u), u the smoothed LFO in [-1, 1]      [fit]
P90_KNEE = 3.892         # JFET leg: R = (RS^m + R_ch^m)^(1/m), sharpness m of the series limit  [fit]
P90_BETA = 0.3957        # block logo: op-amp feedback resistor / feedback resistor (R15 in Eichas) [fit]
P90_KAPPA = -0.002       # LFO curvature: RC charge halves, 0 = straight triangle                [fit]
P90_GATE_HZ = 3.535      # one-pole smoothing between LFO and JFET gates                          [fit]
P90_FB_LAG_HZ = 11736.0  # block logo: one-pole lag in the feedback-resistor path (sets notch depth) [fit]

# ------------------------------------------------------------- Small Stone constants
SS_OFF = dict(f_lo=355.0, f_hi=8300.0, c=0.0, dry=0.75, wet=0.50)     # dry/wet: fit.py from depth and peak
# Color on: feedback c around all four stages through the Color network's highpass branch, the
# wet input through its shaping branch. The network has two real poles f_p1 < f_p2 shared by
# both branches (one RC network, two taps). All values: fit.py from targets.tsv.   [fit]
SS_ON = dict(f_lo=99.0, f_hi=3133.5, c=0.7553, dry=0.1266, wet=0.4289,
             f_p1=53.0, f_p2=266.0,      # network poles, Hz
             f_zf=18.3,                  # feedback branch zero (second zero is at DC), Hz
             f_za=16.5, f_zb=885.2)      # input branch zeros, Hz
SS_KAPPA = 0.70          # LFO curvature


def read_wav(path):
    raw = open(path, "rb").read()
    pos, fmt, data = 12, None, None
    while pos + 8 <= len(raw):
        tag, size = raw[pos:pos + 4], struct.unpack("<I", raw[pos + 4:pos + 8])[0]
        chunk = raw[pos + 8:pos + 8 + size]
        if tag == b"fmt ":
            fmt = struct.unpack("<HHIIHH", chunk[:16])
        elif tag == b"data":
            data = chunk
        pos += 8 + size + (size & 1)
    code, channels, sr, _, _, bits = fmt
    if code == 0xFFFE:
        code = 3 if bits == 32 else 1
    if code == 3:
        samples = np.frombuffer(data, "<f4" if bits == 32 else "<f8").astype(np.float64)
    elif bits == 16:
        samples = np.frombuffer(data, "<i2") / 32768.0
    elif bits == 24:
        b = np.frombuffer(data, np.uint8).reshape(-1, 3).astype(np.int32)
        samples = ((b[:, 0] | (b[:, 1] << 8) | (b[:, 2] << 16)) << 8 >> 8) / 8388608.0
    else:
        samples = np.frombuffer(data, "<i4") / 2147483648.0
    return samples.reshape(-1, channels).T, sr


def write_wav(path, data, sr):
    data = np.atleast_2d(np.asarray(data, dtype=np.float32))
    channels, frames = data.shape
    body = data.T.astype("<f4").tobytes()
    header = b"RIFF" + struct.pack("<I", 36 + len(body)) + b"WAVEfmt " + struct.pack(
        "<IHHIIHH", 16, 3, channels, int(sr), int(sr) * channels * 4, channels * 4, 32)
    open(path, "wb").write(header + b"data" + struct.pack("<I", len(body)) + body)


def rc_triangle(phase, kappa):
    """Relaxation-oscillator triangle in [-1, 1]: each half is an RC charge curve.
    kappa -> 0 is a straight triangle. phase in [0, 1)."""
    up = phase < 0.5
    u = np.where(up, 2.0 * phase, 2.0 * phase - 1.0)
    s = u if abs(kappa) < 1e-9 else (1.0 - np.exp(-kappa * u)) / (1.0 - math.exp(-kappa))
    return np.where(up, 2.0 * s - 1.0, 1.0 - 2.0 * s)


def lfo(n, fs, rate_hz, kappa, phase0=0.0):
    return rc_triangle((phase0 + rate_hz * np.arange(n) / fs) % 1.0, kappa)


def phase90_leg_ohm(u):
    """Resistance of one stage's JFET leg against the smoothed LFO u (+1 = top of the sweep):
    an exponential channel resistance soft-limited from below by a series resistance."""
    r_ch = P90_R1 * np.exp(-P90_GAMMA * u)
    return (P90_RS ** P90_KNEE + r_ch ** P90_KNEE) ** (1.0 / P90_KNEE)


def phase90_break_hz(n, fs, rate_hz, depth, phase0=0.0):
    """Per-sample allpass break frequency of the Phase 90 voicing: LFO -> gate smoothing ->
    JFET leg (in parallel with the fixed 22k) with the 47 nF capacitor."""
    v = lfo(n, fs, rate_hz, P90_KAPPA, phase0)
    k = 1.0 - math.exp(-2.0 * math.pi * P90_GATE_HZ / fs)       # gate RC
    s = v[0]
    for i in range(n):
        s += k * (v[i] - s)
        v[i] = s
    u = v * (depth / 0.5)
    return (1.0 / P90_RFIX + 1.0 / phase90_leg_ohm(u)) / (2.0 * math.pi * P90_C)


def smallstone_break_hz(n, fs, rate_hz, depth, color, phase0=0.0):
    p = SS_ON if color else SS_OFF
    v = lfo(n, fs, rate_hz, SS_KAPPA, phase0)
    centre = math.sqrt(p["f_lo"] * p["f_hi"])
    half_log = 0.5 * math.log(p["f_hi"] / p["f_lo"]) * min(depth / 0.5, 1.2)
    return centre * np.exp(half_log * v)


def run_phase90(x, fs, fc, block, mix):
    """A = (w-1)/(w+1) per stage (the op-amp stage: -1 at DC, +1 at HF)."""
    beta = P90_BETA if block else 0.0
    gl = math.tan(math.pi * min(P90_FB_LAG_HZ, 0.49 * fs) / fs); GL = gl / (1.0 + gl)
    sl = 0.0                                    # feedback lag state
    g = np.tan(np.pi * np.minimum(fc, 0.49 * fs) / fs)
    big_g = g / (1.0 + g)
    s1 = s2 = s3 = s4 = 0.0
    y = np.empty(np.shape(x))      # x: (frames,) or (frames, channels)
    for n in range(len(x)):
        G = big_g[n]
        a = 1.0 - 2.0 * G                       # instantaneous gain of one allpass
        xin = x[n]
        # stage 1: plain allpass
        v = (xin - s1) * G; lp = v + s1; s1 = lp + v
        v1 = xin - 2.0 * lp
        # stage 2: non-inverting gain 2+beta because the feedback resistor loads the inverting input
        v = (v1 - s2) * G; lp = v + s2; s2 = lp + v
        s2out = (1.0 + beta) * v1 - (2.0 + beta) * lp
        # stages 3 and 4 inside the feedback loop, solved without a delay:
        #   u = s2out - beta*L(y4),  L(y4) = GL*y4 + (1-GL)*sl (lag),  y4 = a*(a*u + k3) + k4
        k3 = -2.0 * (1.0 - G) * s3
        k4 = -2.0 * (1.0 - G) * s4
        y4 = (a * a * (s2out - beta * (1.0 - GL) * sl) + a * k3 + k4) / (1.0 + beta * GL * a * a)
        v = (y4 - sl) * GL; lp = v + sl; sl = lp + v
        u = s2out - beta * lp
        v = (u - s3) * G; lp = v + s3; s3 = lp + v
        y3 = u - 2.0 * lp
        v = (y3 - s4) * G; lp = v + s4; s4 = lp + v
        y[n] = (1.0 - mix) * xin + mix * (y3 - 2.0 * lp)
    return y


def tpt_g(f_hz, fs):
    g = math.tan(math.pi * f_hz / fs)
    return g / (1.0 + g)


def run_smallstone(x, fs, fc, color, mix):
    """P = (1-w)/(1+w) per stage. mix 0.5 is the stock dry/wet pair, 0 dry, 1 wet only.

    Color on (all one-poles are TPT lowpasses lp = G*(in - s) + s, s <- 2*lp - s):
      input branch    xs = Sb(Sa(x)),  Sa(v) = v - (1 - f_za/f_p1) * lp1a(v),  Sb(v) = v - (1 - f_zb/f_p2) * lp2a(v)
                      = (s + w_za)(s + w_zb) / ((s + w_p1)(s + w_p2))
      feedback branch F(y) = Sf(y - lp1f(y)),  Sf(v) = v - (1 - f_zf/f_p2) * lp2f(v)
                      = s (s + w_zf) / ((s + w_p1)(s + w_p2))
      loop            u = xs + c * F(y4),  y4 = P^4(u), solved per sample without a delay
      out             dry * x + wet * y4
    """
    p = SS_ON if color else SS_OFF
    c = p["c"]
    dry = p["dry"] * min(1.0, 2.0 * (1.0 - mix))
    wet = p["wet"] * min(1.0, 2.0 * mix)
    g = np.tan(np.pi * np.minimum(fc, 0.49 * fs) / fs)
    big_g = g / (1.0 + g)
    if color:
        G1, G2 = tpt_g(p["f_p1"], fs), tpt_g(p["f_p2"], fs)
        ka, kb, kf = 1.0 - p["f_za"] / p["f_p1"], 1.0 - p["f_zb"] / p["f_p2"], 1.0 - p["f_zf"] / p["f_p2"]
        aF = (1.0 - G1) * (1.0 - kf * G2)     # instantaneous gain of F
    st = [0.0, 0.0, 0.0, 0.0]
    s1a = s2a = 0.0  # input branch states
    s1f = s2f = 0.0  # feedback branch states
    y = np.empty(np.shape(x))      # x: (frames,) or (frames, channels)
    for n in range(len(x)):
        G = big_g[n]
        pg = 2.0 * G - 1.0
        xin = x[n]
        K = 0.0          # y4 = pg^4 * u + K
        for k in range(4):
            K = pg * K + 2.0 * (1.0 - G) * st[k]
        p4 = pg * pg * pg * pg
        if color:
            v = (xin - s1a) * G1; lp = v + s1a; s1a = lp + v
            xa = xin - ka * lp
            v = (xa - s2a) * G2; lp = v + s2a; s2a = lp + v
            xs = xa - kb * lp
            # F(y4) = aF * y4 + bF  (affine in y4 for this sample)
            bF = -(1.0 - kf * G2) * (1.0 - G1) * s1f - kf * (1.0 - G2) * s2f
            y4 = (p4 * (xs + c * bF) + K) / (1.0 - c * aF * p4)
            v = (y4 - s1f) * G1; lp = v + s1f; s1f = lp + v
            h = y4 - lp
            v = (h - s2f) * G2; lp = v + s2f; s2f = lp + v
            u = xs + c * (h - kf * lp)
        else:
            u = xin
        for k in range(4):
            v = (u - st[k]) * G; lp = v + st[k]; st[k] = lp + v
            u = 2.0 * lp - u
        y[n] = dry * xin + wet * u
    return y


def render(x, fs, voicing, rate=1.0, depth=0.5, mix=0.5, block=False, color=False):
    if voicing == "phase90":
        return run_phase90(x, fs, phase90_break_hz(len(x), fs, rate, depth), block, mix)
    return run_smallstone(x, fs, smallstone_break_hz(len(x), fs, rate, depth, color), color, mix)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("inp"); ap.add_argument("out")
    ap.add_argument("--voicing", choices=("phase90", "smallstone"), required=True)
    ap.add_argument("--block", action="store_true"); ap.add_argument("--color", action="store_true")
    ap.add_argument("--rate", type=float, default=None)
    ap.add_argument("--depth", type=float, default=0.5); ap.add_argument("--mix", type=float, default=0.5)
    a = ap.parse_args()
    x, fs = read_wav(a.inp)
    rate = a.rate if a.rate is not None else (1.0 if a.voicing == "phase90" else 0.32)
    out = [render(ch, fs, a.voicing, rate, a.depth, a.mix, a.block, a.color) for ch in x]
    write_wav(a.out, np.array(out), fs)
    print(f"{a.out}\t{len(x[0])} frames\t{fs} Hz\tpeak {20*np.log10(np.max(np.abs(out))+1e-12):.2f} dBFS", file=sys.stderr)


if __name__ == "__main__":
    main()
